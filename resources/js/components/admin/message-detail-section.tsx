/*
 * "Details" section on the message edit page (master–detail).
 * Generated by the CRUD generator — edit freely.
 */

/** Row actions; managing details follows the parent's "update" ability. */
function RowMenu({ item }: { item: MessageDetail }) {
    const { abilities } = usePage<{ abilities: { update: boolean } }>().props;

    if (!abilities.update) {
        return null;
    }

    const route = { message: item.msg_id, detail: item.id };
    const actions: RowAction[] = [
        {
            type: 'link',
            label: 'Edit',
            icon: Pencil,
            href: MessageDetailController.edit(route),
        },
        {
            type: 'confirm',
            label: 'Delete',
            icon: Trash2,
            destructive: true,
            confirm: {
                title: `Delete detail #${item.id}?`,
                description:
                    'This row will be permanently deleted. This action cannot be undone.',
                confirmLabel: 'Delete',
            },
            onConfirm: (close) =>
                router.visit(MessageDetailController.destroy(route), {
                    preserveScroll: true,
                    onFinish: close,
                }),
        },
    ];

    return (
        <RowActions
            label={`Actions for detail #${item.id}`}
            actions={actions}
        />
    );
}

