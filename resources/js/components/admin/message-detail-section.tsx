export function MessageDetailSection({
    parentId,
    details,
    canManage,
}: {
    parentId: number;
    details: Paginated<MessageDetail>;
    canManage: boolean;
}) {
    return (
        <Card className="max-w-full gap-0 overflow-hidden py-0">
            <CardHeader className="flex-row items-center gap-3 border-b py-4">
                <div className="flex size-9 shrink-0 items-center justify-center rounded-lg bg-primary/10 text-primary">
                    <Rows3 className="size-4.5" />
                </div>
                <div className="flex-1 space-y-1">
                    <CardTitle>Details</CardTitle>
                    <CardDescription>
                        {details.total} row{details.total === 1 ? '' : 's'} in{' '}
                        <code>msg_det</code>.
                    </CardDescription>
                </div>
                {canManage && (
                    <Button
                        asChild
                        size="sm"
                        className="shadow-sm shadow-primary/30"
                    >
                        <Link href={MessageDetailController.create(parentId)}>
                            <ListPlus /> Add detail
                        </Link>
                    </Button>
                )}
            </CardHeader>

            <DataTable
                columns={columns}
                data={details.data}
                getRowId={(item) => String(item.id)}
                columnClassNames={{ actions: 'w-12 pr-0' }}
                empty={
                    <EmptyState
                        icon={Inbox}
                        title="No details yet"
                        description="Add the first row to get started."
                    />
                }
            />

            {details.last_page > 1 && (
                <div className="border-t bg-muted/20 px-4 py-3">
                    <Pagination page={details} />
                </div>
            )}
        </Card>
    );
}
