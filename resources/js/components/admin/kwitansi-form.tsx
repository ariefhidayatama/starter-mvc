import { Form, Link } from '@inertiajs/react';
import KwitansiController from '@/actions/App/Http/Controllers/Admin/KwitansiController';

import InputError from '@/components/input-error';
import { Button } from '@/components/ui/button';
import {
    Card,
    CardContent,
    CardDescription,
    CardHeader,
    CardTitle,
} from '@/components/ui/card';
import { Input } from '@/components/ui/input';
import { Label } from '@/components/ui/label';
import { KwitansiKwitansiDetRows } from '@/components/admin/kwitansi-kwitansi-det-rows';
import type { RouteFormDefinition } from '@/wayfinder';

/** A row of the "kwitansis" table (see App\Models\Kwitansi). */
export type Kwitansi = {
    id: number;
    /** Only when the table has a "ulid" column; used in URLs (see routeKey). */
    ulid?: string | null;
    kwitansi_no: string;
    customer: string;
    ship_to: string;
    ttf_no: string;
    created_at: string;
    updated_at: string;
};

/**
 * Kwitansi form shared by the Create & Edit pages.
 * Generated by the CRUD generator — edit freely.
 */
export function KwitansiForm({
    action,
    item,
    cancelHref = KwitansiController.index.url(),
    maxDetails,
}: {
    action: RouteFormDefinition<'post'>;
    item?: Kwitansi;
    /** Where "Cancel" goes back to. */
    cancelHref?: string;
    /**
     * Add page only: rows for kwitansi_kwitansi_dets, saved together with the
     * kwitansi in one transaction. The edit page manages them separately.
     */
    maxDetails?: number;
}) {
    return (
        <Form {...action} className="space-y-6">
            {({ processing, errors }) => (
                <>
                    <Card className="max-w-3xl">
                        <CardHeader>
                            <CardTitle>Kwitansi details</CardTitle>
                            <CardDescription>
                                Fields marked * are required.
                            </CardDescription>
                        </CardHeader>
                        <CardContent className="grid items-start gap-5 sm:grid-cols-2">
                            <div className="grid gap-2">
                                <Label htmlFor="kwitansi_no" required>
                                    Kwitansi no
                                </Label>
                                <Input
                                    id="kwitansi_no"
                                    name="kwitansi_no"
                                    maxLength={50}
                                    defaultValue={item?.kwitansi_no ?? ''}
                                    required
                                />
                                <InputError message={errors.kwitansi_no} />
                            </div>

                            <div className="grid gap-2">
                                <Label htmlFor="customer" required>
                                    Customer
                                </Label>
                                <Input
                                    id="customer"
                                    name="customer"
                                    maxLength={100}
                                    defaultValue={item?.customer ?? ''}
                                    required
                                />
                                <InputError message={errors.customer} />
                            </div>

                            <div className="grid gap-2">
                                <Label htmlFor="ship_to" required>
                                    Ship to
                                </Label>
                                <Input
                                    id="ship_to"
                                    name="ship_to"
                                    maxLength={100}
                                    defaultValue={item?.ship_to ?? ''}
                                    required
                                />
                                <InputError message={errors.ship_to} />
                            </div>

                            <div className="grid gap-2">
                                <Label htmlFor="ttf_no" required>
                                    Ttf no
                                </Label>
                                <Input
                                    id="ttf_no"
                                    name="ttf_no"
                                    maxLength={50}
                                    defaultValue={item?.ttf_no ?? ''}
                                    required
                                />
                                <InputError message={errors.ttf_no} />
                            </div>
                        </CardContent>
                    </Card>

                    {maxDetails !== undefined && (
                        <>
                            <KwitansiKwitansiDetRows
                                errors={errors}
                                max={maxDetails}
                            />
                        </>
                    )}
                    <div className="flex items-center justify-end gap-2">
                        <Button variant="ghost" asChild>
                            <Link href={cancelHref}>Cancel</Link>
                        </Button>
                        <Button
                            disabled={processing}
                            className="shadow-sm shadow-primary/30"
                        >
                            {item ? 'Save changes' : 'Create kwitansi'}
                        </Button>
                    </div>
                </>
            )}
        </Form>
    );
}
