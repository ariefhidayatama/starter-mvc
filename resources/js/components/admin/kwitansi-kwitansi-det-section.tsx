import { createColumnHelper } from '@tanstack/react-table';
import { Inbox, ListPlus, Pencil, Rows3, Trash2 } from 'lucide-react';
import KwitansiKwitansiDetController from '@/actions/App/Http/Controllers/Admin/KwitansiKwitansiDetController';
import type { KwitansiKwitansiDet } from '@/components/admin/kwitansi-kwitansi-det-form';
import {
    DataTable,
    dataTableFeatures,
} from '@/components/data-table/data-table';
import { EmptyState } from '@/components/empty-state';
import { Pagination } from '@/components/pagination';
import { RowActions } from '@/components/row-actions';
import type { RowAction } from '@/components/row-actions';
import { Button } from '@/components/ui/button';
import {
    Card,
    CardDescription,
    CardHeader,
    CardTitle,
} from '@/components/ui/card';
import { routeKey } from '@/lib/route-key';
import type { RouteKey } from '@/lib/route-key';
import type { Paginated } from '@/types';

/*
 * "Kwitansi dets" section on the kwitansi edit page (master–detail).
 * Generated by the CRUD generator — edit freely.
 */

/** Row actions; managing kwitansi dets follows the parent's "update" ability. */
function RowMenu({
    item,
    parentKey,
}: {
    item: KwitansiKwitansiDet;
    parentKey: RouteKey;
}) {
    const { abilities } = usePage<{ abilities: { update: boolean } }>().props;

    if (!abilities.update) {
        return null;
    }

    const route = { kwitansi: parentKey, kwitansi_det: routeKey(item) };
    const actions: RowAction[] = [
        {
            type: 'link',
            label: 'Edit',
            icon: Pencil,
            href: KwitansiKwitansiDetController.edit(route),
        },
        {
            type: 'confirm',
            label: 'Delete',
            icon: Trash2,
            destructive: true,
            confirm: {
                title: `Delete kwitansi det #${item.id}?`,
                description:
                    'This row will be permanently deleted. This action cannot be undone.',
                confirmLabel: 'Delete',
            },
            onConfirm: (close) =>
                router.visit(KwitansiKwitansiDetController.destroy(route), {
                    preserveScroll: true,
                    onFinish: close,
                }),
        },
    ];

    return (
        <RowActions
            label={`Actions for kwitansi det #${item.id}`}
            actions={actions}
        />
    );
}

const column = createColumnHelper<
    typeof dataTableFeatures,
    KwitansiKwitansiDet
>();

/** Columns need the parent's route key (ulid or id) for the row actions. */
const makeColumns = (parentKey: RouteKey) =>
    column.columns([
        column.display({
            id: 'actions',
            header: () => <span className="sr-only">Actions</span>,
            cell: ({ row }) => (
                <RowMenu item={row.original} parentKey={parentKey} />
            ),
        }),
        column.accessor('customer_po', {
            header: 'Customer po',
            cell: ({ row }) => (
                <span className="font-medium">
                    {row.original.customer_po ?? '-'}
                </span>
            ),
        }),
        column.accessor('si_no', {
            header: 'Si no',
            cell: ({ row }) => (
                <span className="font-medium">{row.original.si_no ?? '-'}</span>
            ),
        }),
    ]);

export function KwitansiKwitansiDetSection({
    parentKey,
    details,
    canManage,
}: {
    /** The parent's ulid (or id when its table has no ulid column). */
    parentKey: RouteKey;
    details: Paginated<KwitansiKwitansiDet>;
    canManage: boolean;
}) {
    const columns = makeColumns(parentKey);

    return (
        <Card className="max-w-full gap-0 overflow-hidden py-0">
            <CardHeader className="flex-row items-center gap-3 border-b py-4">
                <div className="flex size-9 shrink-0 items-center justify-center rounded-lg bg-primary/10 text-primary">
                    <Rows3 className="size-4.5" />
                </div>
                <div className="flex-1 space-y-1">
                    <CardTitle>Kwitansi dets</CardTitle>
                    <CardDescription>
                        {details.total} row{details.total === 1 ? '' : 's'} in{' '}
                        <code>kwitansi_kwitansi_dets</code>.
                    </CardDescription>
                </div>
                {canManage && (
                    <Button
                        asChild
                        size="sm"
                        className="shadow-sm shadow-primary/30"
                    >
                        <Link
                            href={KwitansiKwitansiDetController.create(
                                parentKey,
                            )}
                        >
                            <ListPlus /> Add kwitansi det
                        </Link>
                    </Button>
                )}
            </CardHeader>

            <DataTable
                columns={columns}
                data={details.data}
                getRowId={(item) => String(item.id)}
                columnClassNames={{ actions: 'w-12 pr-0' }}
                empty={
                    <EmptyState
                        icon={Inbox}
                        title="No kwitansi dets yet"
                        description="Add the first row to get started."
                    />
                }
            />

            {details.last_page > 1 && (
                <div className="border-t bg-muted/20 px-4 py-3">
                    <Pagination page={details} />
                </div>
            )}
        </Card>
    );
}
