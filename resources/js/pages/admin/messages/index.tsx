type Filters = { search: string; sort: string; per_page: number };

/** What the user may do: app permission AND the database account's rights. */
type Abilities = { create: boolean; update: boolean; delete: boolean };

/** Row actions as a component, so it can read page props (usePage). */
function RowMenu({ item }: { item: Message }) {
    const { abilities } = usePage<{ abilities: Abilities }>().props;
    const actions: RowAction[] = [];

    if (abilities.update) {
        actions.push({
            type: 'link',
            label: 'Edit',
            icon: Pencil,
            href: MessageController.edit(item.id),
        });
    }

    if (abilities.delete) {
        actions.push({
            type: 'confirm',
            label: 'Delete',
            icon: Trash2,
            destructive: true,
            confirm: {
                title: `Delete ${item.whs_code}?`,
                description:
                    'This message will be permanently deleted. This action cannot be undone.',
                confirmLabel: 'Delete',
            },
            onConfirm: (close) =>
                router.visit(MessageController.destroy(item.id), {
                    preserveScroll: true,
                    onFinish: close,
                }),
        });
    }

    return (
        <RowActions label={`Actions for ${item.whs_code}`} actions={actions} />
    );
}

