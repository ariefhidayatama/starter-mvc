import { Head, Link, router, usePage } from '@inertiajs/react';
import { createColumnHelper } from '@tanstack/react-table';
import { Inbox, Pencil, Plus, Search, Table2, Trash2 } from 'lucide-react';
import KwitansiController from '@/actions/App/Http/Controllers/Admin/KwitansiController';
import type { Kwitansi } from '@/components/admin/kwitansi-form';
import {
    DataTable,
    dataTableFeatures,
} from '@/components/data-table/data-table';
import { EmptyState } from '@/components/empty-state';
import { PageHeader } from '@/components/page-header';
import { Pagination } from '@/components/pagination';
import { RowActions } from '@/components/row-actions';
import type { RowAction } from '@/components/row-actions';
import { Button } from '@/components/ui/button';
import { Card } from '@/components/ui/card';
import { Input } from '@/components/ui/input';
import { useTableQuery } from '@/hooks/use-table-query';
import { routeKey } from '@/lib/route-key';
import type { Paginated } from '@/types';

/*
 * Kwitansis: list page. Generated by the CRUD generator — edit freely.
 */

type Filters = { search: string; sort: string; per_page: number };

/** What the user may do: app permission AND the database account's rights. */
type Abilities = { create: boolean; update: boolean; delete: boolean };

/** Row actions as a component, so it can read page props (usePage). */
function RowMenu({ item }: { item: Kwitansi }) {
    const { abilities } = usePage<{ abilities: Abilities }>().props;
    const actions: RowAction[] = [];

    if (abilities.update) {
        actions.push({
            type: 'link',
            label: 'Edit',
            icon: Pencil,
            href: KwitansiController.edit(routeKey(item)),
        });
    }

    if (abilities.delete) {
        actions.push({
            type: 'confirm',
            label: 'Delete',
            icon: Trash2,
            destructive: true,
            confirm: {
                title: `Delete ${item.kwitansi_no}?`,
                description:
                    'This kwitansi will be permanently deleted. This action cannot be undone.',
                confirmLabel: 'Delete',
            },
            onConfirm: (close) =>
                router.visit(KwitansiController.destroy(routeKey(item)), {
                    preserveScroll: true,
                    onFinish: close,
                }),
        });
    }

    return (
        <RowActions
            label={`Actions for ${item.kwitansi_no}`}
            actions={actions}
        />
    );
}

/** Sortable column ids must match SORTS in KwitansiController. */
const column = createColumnHelper<typeof dataTableFeatures, Kwitansi>();

const columns = column.columns([
    column.display({
        id: 'actions',
        header: () => <span className="sr-only">Actions</span>,
        cell: ({ row }) => <RowMenu item={row.original} />,
    }),
    column.accessor('kwitansi_no', {
        header: 'Kwitansi no',
        enableSorting: true,
        cell: ({ row }) => (
            <span className="font-medium">
                {row.original.kwitansi_no ?? '-'}
            </span>
        ),
    }),
    column.accessor('customer', {
        header: 'Customer',
        enableSorting: true,
        cell: ({ row }) => (
            <span className="font-medium">{row.original.customer ?? '-'}</span>
        ),
    }),
    column.accessor('ship_to', {
        header: 'Ship to',
        enableSorting: true,
        cell: ({ row }) => (
            <span className="font-medium">{row.original.ship_to ?? '-'}</span>
        ),
    }),
    column.accessor('ttf_no', {
        header: 'Ttf no',
        enableSorting: true,
        cell: ({ row }) => (
            <span className="font-medium">{row.original.ttf_no ?? '-'}</span>
        ),
    }),
]);

export default function KwitansiIndex({
    items,
    filters,
    abilities,
}: {
    items: Paginated<Kwitansi>;
    filters: Filters;
    abilities: Abilities;
}) {
    const { search, setSearch, apply } = useTableQuery(
        KwitansiController.index.url(),
        filters,
        ['items', 'filters'],
    );

    return (
        <>
            <Head title="Kwitansis" />

            <div className="space-y-6 p-4 md:p-6">
                <PageHeader
                    icon={Table2}
                    title="Kwitansis"
                    description="Manage kwitansis."
                />

                <Card className="gap-0 overflow-hidden py-0">
                    {/* Toolbar: [Add] [Search] */}
                    <div className="flex flex-col gap-2 border-b p-4 sm:flex-row sm:items-center">
                        {abilities.create && (
                            <Button
                                asChild
                                className="shrink-0 shadow-sm shadow-primary/30"
                            >
                                <Link href={KwitansiController.create()}>
                                    <Plus /> Add kwitansi
                                </Link>
                            </Button>
                        )}
                        <div className="relative w-full sm:max-w-xs lg:w-72">
                            <Search className="absolute top-1/2 left-3 size-4 -translate-y-1/2 text-muted-foreground" />
                            <Input
                                value={search}
                                onChange={(e) => setSearch(e.target.value)}
                                placeholder="Search kwitansi no or customer…"
                                className="h-9 rounded-lg pl-9"
                                aria-label="Search kwitansi"
                            />
                        </div>
                    </div>

                    <DataTable
                        columns={columns}
                        data={items.data}
                        getRowId={(item) => String(item.id)}
                        sort={filters.sort}
                        onSortChange={(sort) => apply({ sort })}
                        columnClassNames={{ actions: 'w-12 pr-0' }}
                        empty={
                            <EmptyState
                                icon={Inbox}
                                title="No kwitansis found"
                                description={
                                    search
                                        ? 'Try a different keyword.'
                                        : 'Add the first one to get started.'
                                }
                            />
                        }
                    />

                    <div className="border-t bg-muted/20 px-4 py-3">
                        <Pagination
                            page={items}
                            onPerPageChange={(perPage) =>
                                apply({ per_page: perPage })
                            }
                        />
                    </div>
                </Card>
            </div>
        </>
    );
}

KwitansiIndex.layout = {
    breadcrumbs: [{ title: 'Kwitansis', href: KwitansiController.index() }],
};
